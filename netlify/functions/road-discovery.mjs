const OVERPASS_ENDPOINTS = [
  'https://overpass-api.de/api/interpreter',
  'https://overpass.private.coffee/api/interpreter',
]
const UPSTREAM_TIMEOUT_MS = 10_000

function json(statusCode, body) {
  return {
    statusCode,
    headers: {
      'content-type': 'application/json; charset=utf-8',
      'cache-control': 'public, max-age=60, stale-while-revalidate=300',
    },
    body: JSON.stringify(body),
  }
}

export async function handler(event) {
  if (!['GET', 'POST'].includes(event.httpMethod)) return json(405, { error: 'GETまたはPOSTのみ対応しています' })
  let query = ''
  if (event.httpMethod === 'GET') query = event.queryStringParameters?.data || ''
  else {
    try { query = JSON.parse(event.body || '{}').query || '' } catch { return json(400, { error: 'リクエスト形式が不正です' }) }
  }
  // This endpoint is deliberately narrow: it relays only the bounded road
  // discovery query generated by the app, not arbitrary Overpass requests.
  if (typeof query !== 'string' || query.length > 3000 || !query.includes('[out:json]') || !query.includes('way(around:')) return json(400, { error: '道路探索クエリが不正です' })

  let lastError = '道路データを取得できませんでした'
  // Netlify functions have a platform timeout.  Keep individual attempts
  // short so one saturated public mirror cannot consume the entire function
  // and prevent the browser from trying the next route.
  for (const endpoint of OVERPASS_ENDPOINTS) {
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), UPSTREAM_TIMEOUT_MS)
    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'content-type': 'application/x-www-form-urlencoded;charset=UTF-8', 'user-agent': 'Touge-App road discovery/1.0' },
        body: new URLSearchParams({ data: query }),
        signal: controller.signal,
      })
      if (!response.ok) { lastError = `Overpass API ${response.status}`; continue }
      const data = await response.json()
      if (!Array.isArray(data?.elements)) { lastError = 'Overpass APIの応答形式が不正です'; continue }
      return json(200, data)
    } catch (error) { lastError = error instanceof Error ? error.message : lastError } finally { clearTimeout(timer) }
  }
  return json(503, { error: lastError })
}
